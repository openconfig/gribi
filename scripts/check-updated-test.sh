set -euo pipefail

THIS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
SCRIPT_UNDER_TEST="${THIS_DIR}/check-updated.sh"

TMP_ROOT="$(mktemp -d)"
trap 'rm -rf "${TMP_ROOT}"' EXIT

# Isolate from host Git configuration (e.g. commit.gpgsign=true, color.ui=always).
export HOME="${TMP_ROOT}/home"
export XDG_CONFIG_HOME="${TMP_ROOT}/config"
export GIT_CONFIG_NOSYSTEM=1
mkdir -p "${HOME}" "${XDG_CONFIG_HOME}"

PASS_COUNT=0

setup_repo() {
  local repo="${TMP_ROOT}/$1"
  mkdir -p "${repo}/scripts" "${repo}/v1/proto/service" "${repo}/v1/proto/gribi_aft"
  cp "${SCRIPT_UNDER_TEST}" "${repo}/scripts/check-updated.sh"
  chmod +x "${repo}/scripts/check-updated.sh"

  cat > "${repo}/v1/proto/service/gribi.pb.go" <<'EOF'
// Code generated by protoc-gen-go. DO NOT EDIT.
// versions:
// 	protoc-gen-go v1.36.7
// 	protoc        v3.21.12
// source: v1/proto/service/gribi.proto

package service
EOF

  cat > "${repo}/v1/proto/service/gribi_grpc.pb.go" <<'EOF'
// Code generated by protoc-gen-go-grpc. DO NOT EDIT.
// versions:
// - protoc-gen-go-grpc v1.6.1
// - protoc             v3.21.12
// source: v1/proto/service/gribi.proto

package service
EOF

  (
    cd "${repo}" &&
    git init -q &&
    git config user.email "test@example.com" &&
    git config user.name "Test Runner" &&
    git config commit.gpgsign false &&
    git add . &&
    git commit -qm "Initial baseline"
  ) || return 1
  printf '%s\n' "${repo}"
}

assert_exit() {
  local name="$1"
  local expected_rc="$2"
  local repo="$3"
  local actual_rc=0
  local output=""

  output="$(bash "${repo}/scripts/check-updated.sh" 2>&1)" || actual_rc=$?
  if [ "${actual_rc}" -ne "${expected_rc}" ]; then
    printf 'FAIL [%s]: expected exit %d, got %d\nOutput:\n%s\n' \
      "${name}" "${expected_rc}" "${actual_rc}" "${output}" >&2
    exit 1
  fi
  PASS_COUNT=$((PASS_COUNT + 1))
  printf 'PASS [%s] (exit %d)\n' "${name}" "${actual_rc}"
}

# 1. Clean repository should pass.
repo1="$(setup_repo clean_repo)"
assert_exit "clean_repo" 0 "${repo1}"

# 2. Pure generator/protoc version and source header updates should pass
#    (even when color.ui=always and color.diff=always are configured).
repo2="$(setup_repo version_headers_only)"
(
  cd "${repo2}" &&
  git config color.ui always &&
  git config color.diff always
)
cat > "${repo2}/v1/proto/service/gribi.pb.go" <<'EOF'
// Code generated by protoc-gen-go. DO NOT EDIT.
// versions:
// 	protoc-gen-go v1.36.12
// 	protoc        v3.29.3
// source: v1/proto/service/gribi.proto

package service
EOF
cat > "${repo2}/v1/proto/service/gribi_grpc.pb.go" <<'EOF'
// Code generated by protoc-gen-go-grpc. DO NOT EDIT.
// versions:
// - protoc-gen-go-grpc v1.6.2
// - protoc             v3.29.3
// source: v1/proto/service/gribi.proto

package service
EOF
assert_exit "version_headers_only" 0 "${repo2}"

# 3. Multi-line drift in a generated .pb.go file must fail.
repo3="$(setup_repo multiline_drift)"
cat >> "${repo3}/v1/proto/service/gribi.pb.go" <<'EOF'

func unexpectedHelper() string {
	return "drift"
}
EOF
assert_exit "multiline_drift" 1 "${repo3}"

# 4. Single-line code sentinel drift must fail (guards against echo -n "$TDIFF" | wc -l -> 0).
repo4="$(setup_repo single_line_drift)"
printf 'var extraSymbol = 1\n' >> "${repo4}/v1/proto/service/gribi.pb.go"
assert_exit "single_line_drift" 1 "${repo4}"

# 5. Single-line sentinel comment appended to a .pb.go file must fail.
repo5="$(setup_repo sentinel_comment_drift)"
printf '// sentinel-drift-line\n' >> "${repo5}/v1/proto/service/gribi.pb.go"
assert_exit "sentinel_comment_drift" 1 "${repo5}"

# 6. Top-level '// protocol...' comments must NOT be mistaken for '// protoc' headers.
repo6="$(setup_repo protocol_comment_drift)"
printf '// protocol specification comment\n' >> "${repo6}/v1/proto/service/gribi.pb.go"
assert_exit "protocol_comment_drift" 1 "${repo6}"

# 7. Code lines with trailing protoc/source comments must NOT be filtered out.
repo7="$(setup_repo inline_comment_not_ignored)"
printf 'var extraSymbol = 1 // source: v1/proto/service/gribi.proto\n' >> "${repo7}/v1/proto/service/gribi.pb.go"
assert_exit "inline_comment_not_ignored" 1 "${repo7}"

# 8. Staged intentional edits with no further unstaged drift should pass locally.
repo8="$(setup_repo staged_changes_allowed)"
printf 'var stagedSymbol = 1\n' >> "${repo8}/v1/proto/service/gribi.pb.go"
(cd "${repo8}" && git add v1/proto/service/gribi.pb.go)
assert_exit "staged_changes_allowed" 0 "${repo8}"

# 9. Untracked file under v1/proto must fail.
repo9="$(setup_repo untracked_in_v1_proto)"
printf 'package gribi_aft\n' > "${repo9}/v1/proto/gribi_aft/new_file.pb.go"
assert_exit "untracked_in_v1_proto" 1 "${repo9}"

# 10. Unrelated untracked file outside v1/proto should not fail local runs.
repo10="$(setup_repo untracked_outside_v1_proto)"
printf 'local scratch note\n' > "${repo10}/notes.txt"
assert_exit "untracked_outside_v1_proto" 0 "${repo10}"

printf 'All %d check-updated tests passed.\n' "${PASS_COUNT}"
